#!/usr/bin/env python3
"""T0: the four-scenario table and Figure 1, from one command with fixed seeds.

    python scripts/t0_scenarios.py --n-jobs 16 --out artifacts/t0

Runs ``c3.sim.t0``: the calibrated / uniform / context / misreading scenarios of
``c3.sim.positions`` through the real estimators (fit half -> report half), and
the numerical check that the true field term grows with m.  Writes

    table.json    every number, the plan's expected pattern, and any mismatch
    table.tex     the four-scenario table
    figure1.pdf/.png   observed Delta(m), the own-confidence and context-aware
                  predictions, and the ECE line, for the context scenario
    field_growth.png   the true field term against m at several noise levels
    macros.tex    one \\newcommand per headline number

Nothing is tuned to match the plan: mismatches are recorded, not fixed.
"""
from __future__ import annotations

import argparse
import datetime as _dt
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np

from c3 import DEFAULT_KNOTS, N_BOOT
from c3.provenance import collect as provenance
from c3.sim.t0 import T0Config, run_t0

_WORDS = {1: "One", 2: "Two", 4: "Four", 8: "Eight", 16: "Sixteen", 32: "ThirtyTwo"}
_SIGMA_WORDS = {0.25: "Quarter", 0.5: "Half", 1.0: "One", 1.5: "OneHalf", 2.0: "Two"}
_LABELS = {"calibrated": "Perfectly calibrated in every context",
           "uniform": "Miscalibrated the same way in every context",
           "context": "Miscalibration depends on context",
           "misreading": "Errors shared across positions"}

# Reference categorical palette, slots 1-3 (validated: dataviz validate_palette.js,
# light surface, all checks pass; aqua is below 3:1 contrast, so every series also
# carries its own marker shape and the legend names it).
_INK, _INK2, _GRID, _SURFACE = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
_SERIES = ("#2a78d6", "#eb6834", "#1baf7a")


def _ci_tex(cell: dict) -> str:
    lo, hi = cell["ci"]
    return f"${cell['value']:+.3f}$ {{\\scriptsize $[{lo:+.3f}, {hi:+.3f}]$}}"


def write_table_tex(path: Path, res: dict) -> None:
    lines = ["% Generated by scripts/t0_scenarios.py -- do not edit by hand.",
             "\\begin{tabular}{lcccc}", "\\toprule",
             "Scenario & $\\Delta(32)-\\Delta(1)$ & field term, $m=32$ & "
             "$\\beta_z$, no FE & $\\beta_z$, with FE \\\\",
             "\\midrule"]
    for s, r in res["scenarios"].items():
        row = r["row"]
        cells = [_ci_tex(row["contrast"]), _ci_tex(row["field_m32"]),
                 _ci_tex(row["beta_nofe"]), _ci_tex(row["beta_fe"])]
        lines.append(f"{_LABELS[s]} & " + " & ".join(cells) + " \\\\")
        exp = row["expected"]
        obs = row["observed"]
        mark = lambda k: "" if row["matches"][k] else "$^{\\dagger}$"  # noqa: E731
        lines.append("\\quad {\\scriptsize plan / observed} & "
                     f"{{\\scriptsize {exp['grows']} / {obs['grows']}{mark('grows')}}} & "
                     f"{{\\scriptsize {exp['field']} / {obs['field']}{mark('field')}}} & "
                     f"{{\\scriptsize {exp['beta_nofe']} / {obs['beta_nofe']}{mark('beta_nofe')}}} & "
                     f"{{\\scriptsize {exp['beta_fe']} / {obs['beta_fe']}{mark('beta_fe')}}} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}",
              "% dagger: observed pattern differs from the plan's expectation."]
    path.write_text("\n".join(lines).replace("!=0", "$\\neq 0$").replace(">0", "$>0$")
                    .replace("<0", "$<0$") + "\n", encoding="utf-8")


def write_macros(path: Path, res: dict) -> None:
    out = ["% Generated by scripts/t0_scenarios.py -- do not edit by hand.",
           f"% commit: {res['provenance']['git_commit']}"]

    def add(name, value, fmt="{:.3f}"):
        if any(ch.isdigit() for ch in name):
            raise ValueError(f"macro name {name!r} contains a digit")
        out.append(f"\\newcommand{{\\TZero{name}}}{{{fmt.format(value)}}}")

    for s, r in res["scenarios"].items():
        tag, row = s.title(), r["row"]
        for key, name in (("contrast", "Contrast"), ("field_m32", "Field"),
                          ("field_m32_true", "FieldTrue"), ("beta_nofe", "BetaZNoFE"),
                          ("beta_fe", "BetaZFE")):
            if key in row:
                add(f"{name}{tag}", row[key]["value"])
                add(f"{name}{tag}Lo", row[key]["ci"][0])
                add(f"{name}{tag}Hi", row[key]["ci"][1])
        add(f"ECE{tag}", r["ece"]["value"])
        add(f"ICC{tag}", r["icc_residuals"]["icc"])

    ctx = res["scenarios"].get("context")
    if ctx:
        ser = ctx["series"]
        for name, key in (("Gap", "delta"), ("Own", "delta_own"), ("Ctx", "delta_ctx"),
                          ("FieldTerm", "field"), ("Residual", "residual")):
            for m, v in zip(ser[key]["m"], ser[key]["point"]):
                add(f"{name}{_WORDS[m]}", v)
                add(f"{name}{_WORDS[m]}Pct", 100 * v, "{:.1f}")
        add("ECE", ctx["ece"]["value"])
        add("ECEPct", 100 * ctx["ece"]["value"], "{:.1f}")
    for key, g in res["field_growth"].items():
        tag = "Sigma" + _SIGMA_WORDS[float(key)]
        for m, v in zip(g["m"], g["field"]):
            add(f"GrowthField{_WORDS[m]}{tag}", v)
        add(f"GrowthPeakM{tag}", g["m"][int(np.argmax(g["field"]))], "{:d}")
    add("NMismatches", len(res["mismatches"]), "{:d}")
    path.write_text("\n".join(out) + "\n", encoding="utf-8")


def _style(ax):
    ax.set_facecolor(_SURFACE)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(_INK2)
        ax.spines[side].set_linewidth(0.6)
    ax.tick_params(colors=_INK2, labelcolor=_INK, width=0.6, length=3, labelsize=7.5)
    ax.grid(axis="y", color=_GRID, linewidth=0.6, linestyle="-")
    ax.set_axisbelow(True)


def _label_ece(ax, m, ece, ser) -> None:
    """Put the ECE label at the first end/side of its line that no series or band crosses.

    Where the curves sit relative to the ECE line changes with the data, so a
    fixed position collides on some runs; the label covers the two outermost
    points of one end, just above or just below the line.
    """
    keys = ("delta", "delta_own", "delta_ctx")
    lo = min(min(np.asarray(ser[k]["ci"])[:, 0].min(), min(ser[k]["point"])) for k in keys)
    hi = max(max(np.asarray(ser[k]["ci"])[:, 1].max(), max(ser[k]["point"])) for k in keys)
    h = 0.06 * (max(hi, ece) - min(lo, 0.0))
    for idx, x, ha in (((0, 1), m[0], "left"), ((-2, -1), m[-1], "right")):
        for va, (y0, y1) in (("bottom", (ece, ece + h)), ("top", (ece - h, ece))):
            clear = True
            for k in keys:
                ci = np.asarray(ser[k]["ci"])
                for i in idx:
                    band = (min(ci[i, 0], ser[k]["point"][i]), max(ci[i, 1], ser[k]["point"][i]))
                    if band[0] < y1 and band[1] > y0:
                        clear = False
            if clear:
                ax.text(x, ece, f" ECE = {ece:.3f} ", va=va, ha=ha, fontsize=6.5, color=_INK2)
                return
    ax.text(m[-1], ece, f" ECE = {ece:.3f} ", va="bottom", ha="right", fontsize=6.5,
            color=_INK2, bbox={"facecolor": _SURFACE, "edgecolor": "none", "pad": 0.5})


def figure1(out: Path, res: dict) -> list[str]:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    ctx = res["scenarios"]["context"]
    ser = ctx["series"]
    m = np.asarray(ser["delta"]["m"], dtype=float)
    fig, ax = plt.subplots(figsize=(3.5, 2.9))
    fig.patch.set_facecolor(_SURFACE)
    _style(ax)
    ax.axhline(0, color=_INK2, linewidth=0.6)
    ece = ctx["ece"]["value"]
    ax.axhline(ece, color=_INK2, linewidth=0.8, linestyle=(0, (4, 2)))
    _label_ece(ax, m, ece, ser)
    for (key, label), color, marker in zip(
            (("delta", "Observed gap of the committed token, $\\Delta(m)$"),
             ("delta_own", "Predicted from its own confidence, $\\hat\\pi(\\ell)$"),
             ("delta_ctx", "Predicted with the field's context, $\\hat\\pi(\\ell, s)$")),
            _SERIES, ("o", "s", "^")):
        p = np.asarray(ser[key]["point"])
        ci = np.asarray(ser[key]["ci"])
        ax.fill_between(m, ci[:, 0], ci[:, 1], color=color, alpha=0.12, linewidth=0)
        ax.plot(m, p, color=color, linewidth=1.5, marker=marker, markersize=5,
                markeredgecolor=_SURFACE, markeredgewidth=0.9, solid_capstyle="round",
                label=label)
    ax.set_xscale("log", base=2)
    ax.set_xticks(m, [str(int(v)) for v in m])
    ax.minorticks_off()
    ax.set_xlabel("Field size $m$ (candidates the committed token beat)", fontsize=7.5,
                  color=_INK)
    ax.set_ylabel("confidence $-$ accuracy", fontsize=7.5, color=_INK)
    # Above the axes: inside, it would sit on the confidence bands.
    ax.legend(frameon=False, fontsize=6.3, loc="lower left", bbox_to_anchor=(-0.02, 1.0),
              handlelength=2.2, labelcolor=_INK, borderaxespad=0.2)
    fig.tight_layout(pad=0.4)
    names = []
    for ext in ("pdf", "png"):
        p = out / f"figure1.{ext}"
        fig.savefig(p, dpi=300, facecolor=_SURFACE)
        names.append(p.name)
    plt.close(fig)
    return names


def growth_figure(out: Path, res: dict) -> str:
    """Small multiples: one panel per noise level, so no colour has to carry sigma."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    g = res["field_growth"]
    keys = list(g)
    fig, axes = plt.subplots(1, len(keys), figsize=(1.45 * len(keys) + 0.4, 1.9), sharey=True)
    fig.patch.set_facecolor(_SURFACE)
    for ax, key in zip(np.atleast_1d(axes), keys):
        _style(ax)
        r = g[key]
        m = np.asarray(r["m"], dtype=float)
        ci = np.asarray(r["ci"])
        ax.axhline(0, color=_INK2, linewidth=0.6)
        ax.fill_between(m, ci[:, 0], ci[:, 1], color=_SERIES[0], alpha=0.12, linewidth=0)
        ax.plot(m, r["field"], color=_SERIES[0], linewidth=1.5, marker="o", markersize=4,
                markeredgecolor=_SURFACE, markeredgewidth=0.8)
        ax.set_xscale("log", base=2)
        ax.set_xticks(m, [str(int(v)) for v in m], fontsize=6)
        ax.minorticks_off()
        ax.set_title(f"noise $\\sigma$ = {float(key):g}", fontsize=7, color=_INK)
        ax.set_xlabel("$m$", fontsize=7, color=_INK)
    np.atleast_1d(axes)[0].set_ylabel("true field term", fontsize=7, color=_INK)
    fig.tight_layout(pad=0.4)
    p = out / "field_growth.png"
    fig.savefig(p, dpi=300, facecolor=_SURFACE)
    plt.close(fig)
    return p.name


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--n-docs", type=int, default=200)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--n-boot", type=int, default=N_BOOT)
    ap.add_argument("--eq-boot", type=int, default=None, help="Eq. 2 resamples (default --n-boot)")
    ap.add_argument("--knots", type=int, default=DEFAULT_KNOTS)
    ap.add_argument("--noise-levels", type=float, nargs="*",
                    default=list(T0Config.noise_levels))
    ap.add_argument("--check-docs", type=int, default=T0Config.check_docs)
    ap.add_argument("--check-boot", type=int, default=T0Config.check_boot)
    ap.add_argument("--n-jobs", type=int, default=1)
    ap.add_argument("--no-figures", action="store_true")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    cfg = T0Config(n_docs=a.n_docs, seed=a.seed, n_boot=a.n_boot,
                   eq_boot=a.eq_boot if a.eq_boot is not None else a.n_boot, knots=a.knots,
                   n_jobs=a.n_jobs, noise_levels=tuple(a.noise_levels),
                   check_docs=a.check_docs, check_boot=a.check_boot)
    res = run_t0(cfg)
    res["provenance"] = provenance()
    res["generated_at"] = _dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds")
    res["sign"] = "conf - agree (positive = overconfident)"

    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    if not a.no_figures:
        res["figures"] = figure1(out, res)
        if res["field_growth"]:
            res["figures"].append(growth_figure(out, res))
    (out / "table.json").write_text(json.dumps(res, indent=2, default=float), encoding="utf-8")
    write_table_tex(out / "table.tex", res)
    write_macros(out / "macros.tex", res)

    for s, r in res["scenarios"].items():
        row = r["row"]
        print(f"[t0] {s:10s} grows={row['grows']:3s} contrast={row['contrast']['value']:+.3f} "
              f"field32={row['field_m32']['value']:+.3f} beta_z nofe={row['beta_nofe']['value']:+.3f} "
              f"fe={row['beta_fe']['value']:+.3f}")
    for k, g in res["field_growth"].items():
        print(f"[t0] true field term, sigma={k}: " + " ".join(f"{v:+.3f}" for v in g["field"]))
    print(f"[t0] {len(res['mismatches'])} cells differ from the plan's pattern")
    for mm in res["mismatches"]:
        print(f"[t0]   {mm}")
    print(f"[t0] -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
